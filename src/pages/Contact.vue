import emailjs from '@emailjs/browser'
import LayoutBase from '../components/LayoutBase.vue'
import Navbar from '../components/Navbar.vue'

export default {
  name: 'Contact',
  components: { LayoutBase, Navbar },
  data() {
    return { name: '', email: '', message: '', status: '' }
  },
  methods: {
    sendEmail() {
      const serviceID = import.meta.env.VITE_EMAILJS_SERVICE_ID
      const templateID = import.meta.env.VITE_EMAILJS_TEMPLATE_ID
      const publicKey = import.meta.env.VITE_EMAILJS_PUBLIC_KEY
      const templateParams = { from_name: this.name, from_email: this.email, message: this.message }

      emailjs.send(serviceID, templateID, templateParams, { publicKey })
        .then(() => {
          this.status = 'Mensaje enviado correctamente. ¡Gracias por escribir!'
          this.name = ''
          this.email = ''
          this.message = ''
        })
        .catch((err) => {
          console.error(err)
          this.status = 'No se ha podido enviar el mensaje. Inténtalo de nuevo.'
        })
    }
  }
}
</script>

